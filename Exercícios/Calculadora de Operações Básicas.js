// Pede o primeiro número e transforma a resposta em número
let operacoes = Number(prompt("Digite o primeiro número:"));

// Pede o segundo número e transforma a resposta em número
let operacoes2 = Number(prompt("Digite o segundo número:"));

// Realiza a soma dos dois números
let soma = operacoes + operacoes2;

// Realiza a subtração dos dois números
let subtracao = operacoes - operacoes2;

// Realiza a multiplicação dos dois números
let multiplicacao = operacoes * operacoes2;

// Realiza a divisão dos dois números
let divisao = operacoes / operacoes2;

// Mostra todos os resultados na tela
alert(`Seus resultados foram:
Soma = ${soma}
Subtração = ${subtracao}
Multiplicação = ${multiplicacao}
Divisão = ${divisao}`);
